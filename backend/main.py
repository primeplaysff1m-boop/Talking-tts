"""
Vocalis API
-----------
Text-to-speech backend, with a free daily credit system per device
(no login required — a random device id is generated by the frontend
and stored in its browser localStorage).

Endpoints:
  GET  /               -> health check
  GET  /voices?lang=..  -> list available voices (optionally filtered by locale)
  GET  /languages       -> list available locales
  GET  /credits          -> check a device's remaining credits (does not deduct)
  POST /speak            -> { text, voice, rate, pitch } -> returns MP3 audio
                             requires header X-Device-Id
                             optional header X-Usage-Type: "audio" (default) or "video"

Setup:
  Add these environment variables in Vercel (Project Settings -> Environment Variables):
    SUPABASE_URL          -> from Supabase Project Settings -> API
    SUPABASE_SERVICE_KEY   -> the "service_role" secret key (NOT the anon key)
  Then run credits_schema.sql once in Supabase's SQL editor.
"""

from fastapi import FastAPI, HTTPException, Response, Header
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel
import edge_tts
import asyncio
import time
import os
import datetime

app = FastAPI(title="Vocalis API", version="1.1.0")

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["*"],
    allow_headers=["*"],
    expose_headers=["X-Credits-Remaining"],
)

_voice_cache: list[dict] | None = None

# ---------------------------------------------------------------------------
# Credits
# ---------------------------------------------------------------------------

DAILY_FREE_CREDITS = 30
COST_AUDIO = 1
COST_VIDEO = 5

_supabase = None


def _get_supabase():
    """Lazily create the Supabase client using the service role key.
    Returns None if env vars are not configured yet, so the API still
    runs (with credits effectively unlimited) before setup is finished."""
    global _supabase
    if _supabase is not None:
        return _supabase
    url = os.environ.get("SUPABASE_URL")
    key = os.environ.get("SUPABASE_SERVICE_KEY")
    if not url or not key:
        return None
    try:
        from supabase import create_client
        _supabase = create_client(url, key)
        return _supabase
    except Exception as e:
        print(f"[credits] Supabase client failed to init: {e}", flush=True)
        return None


def _check_and_deduct_credits(device_id: str, cost: int) -> int:
    """Returns remaining credits after deducting `cost`.
    Raises HTTPException(429) if the device has run out.
    If Supabase isn't configured yet, credits are not enforced (returns -1)."""
    sb = _get_supabase()
    if sb is None:
        return -1  # credits not enforced yet

    today = datetime.date.today().isoformat()
    row = sb.table("device_credits").select("*").eq("device_id", device_id).execute()

    if row.data:
        record = row.data[0]
        credits = record["credits"]
        last_reset = record["last_reset"]
        if last_reset != today:
            credits = DAILY_FREE_CREDITS
    else:
        credits = DAILY_FREE_CREDITS

    if credits < cost:
        raise HTTPException(
            status_code=429,
            detail=f"Out of free credits for today (need {cost}, have {credits}). "
                   f"Credits reset at midnight.",
        )

    remaining = credits - cost
    sb.table("device_credits").upsert({
        "device_id": device_id,
        "credits": remaining,
        "last_reset": today,
    }).execute()
    return remaining


@app.get("/credits")
async def get_credits(x_device_id: str | None = Header(default=None)):
    if not x_device_id:
        raise HTTPException(status_code=400, detail="X-Device-Id header is required")
    sb = _get_supabase()
    if sb is None:
        return {"credits": None, "enforced": False, "daily_limit": DAILY_FREE_CREDITS}

    today = datetime.date.today().isoformat()
    row = sb.table("device_credits").select("*").eq("device_id", x_device_id).execute()
    if row.data:
        record = row.data[0]
        credits = record["credits"] if record["last_reset"] == today else DAILY_FREE_CREDITS
    else:
        credits = DAILY_FREE_CREDITS
    return {"credits": credits, "enforced": True, "daily_limit": DAILY_FREE_CREDITS}


